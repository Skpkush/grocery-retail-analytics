def _tables_section(con_rows) -> list[str]:
    lines = ["| Table | Grain | Key | Joins to | Rows |", "| --- | --- | --- | --- | ---: |"]
    for table, (grain, key, joins) in GRAIN.items():
        lines.append(f"| `{table}` | {grain} | {key} | {joins} | {con_rows.get(table, 0):,} |")
    return lines


